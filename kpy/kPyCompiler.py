"""kPyCompiler - writes a product's GENERATED Python modules from the kSharedPy master (the kPS idea for Python).

A product keeps a kpy.manifest.json. Each entry in its "Modules" names one output file inside the product and the
master parts it is made of; "Settings" fill the master lines marked "# kpy:setting <Name>". The output starts with
a header naming the master and the SHA-256 of the body, so a hand edit is found without the master at hand.

    python kPyCompiler.py --manifest <product>\\kpy.manifest.json                 # Check: read-only, the default
    python kPyCompiler.py --manifest ... --action compile                         # write the outputs
    python kPyCompiler.py --manifest ... --action compile --adopt                 # first run: replace a hand copy
    python kPyCompiler.py --manifest ... --action verify                          # CI: exit 5 if anything is off
    python kPyCompiler.py --manifest ... --action verify --standalone             # CI without the master: hash only
    python kPyCompiler.py --action report --root X:\\Source                         # every product: behind or not

Before anything is written (check, compile, verify) three gates run: every master module an output imports must be
generated beside it (or be the product's own file); no output may carry private material (local paths, URL
signatures, the kPS client-name denylist minus the manifest's AllowNames); every master part must pass
check_kpattern. The header names the master release (the VERSION file).

--shared-root (or KPY_SHARED_ROOT) overrides the manifest's SharedRoot, for a clone of the public master repo.
Exit codes: 0 ok; 1 an unexpected error (reported); 2 bad input; 5 verify found a stale, edited or missing output.
"""
import argparse
import ast
import hashlib
import json
import os
import re
import sys

MASTER = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(MASTER, "kshared"))
from kShared import kRun, kS, kToolException, ToolInputException, ToolReportableException  # noqa: E402

COMPILER_VERSION = "1.0"
HEADER_MARK = "# GENERATED by kPyCompiler"
HASH_PATTERN = re.compile(r"^# Body SHA-256: ([0-9a-f]{64})$", re.MULTILINE)
SETTING_PATTERN = re.compile(r"#\s*kpy:setting\s+(\w+)")
EXIT_VERIFY_FAILED = 5
# The same patterns the public-skill publish check refuses (skills/.github/scripts/check_public_leaks.py)
PRIVATE_PATTERNS = [r"[A-Z]:\\Source\\", r"X:[\\/]", r"\bsig=[A-Za-z0-9_\-%]{8,}", r"\\AgentInstruction\\",
                    r"[A-Z]:\\Users\\[^\\\s]+\\AppData"]


class kPyModule:
    """One output file of a product: its master parts, its settings, and the text the master makes of them."""

    def __init__(self, Entry, ManifestDir, SharedRoot):
        try:
            if not isinstance(Entry, dict) or not Entry.get("Out") or not Entry.get("Parts"):
                raise ToolInputException(f"a Modules entry needs \"Out\" and \"Parts\": {Entry!r}")
            self.Out = Entry["Out"]
            self.Parts = list(Entry["Parts"])
            self.Settings = dict(Entry.get("Settings", {}))
            self.ImportPaths = list(Entry.get("ImportPaths", []))  # folders the output puts on sys.path itself
            self.ManifestDir = ManifestDir
            self.SharedRoot = SharedRoot
            self.OutPath = os.path.normpath(os.path.join(ManifestDir, self.Out))
            if os.path.commonpath([self.OutPath, ManifestDir]) != ManifestDir:
                raise ToolInputException(f"{self.Out}: an output must stay inside the product folder")
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.__init__(out={Entry!r})")

    def Build(self):
        """The full generated text (header + body), LF line endings. Raises ToolInputException on a gate failure."""
        if kS.ErrorMode:
            return ""
        try:
            Bodies = []
            Unused = set(self.Settings)
            for Index, Part in enumerate(self.Parts):
                Text = self.ReadPart(Part)
                Text, Applied = self.ApplySettings(Part, Text)
                Unused -= Applied
                if Index > 0 and re.search(r"^from __future__ import", Text, re.MULTILINE):
                    raise ToolInputException(f"{Part}: only the first part of {self.Out} may import from __future__")
                Bodies.append(Text.rstrip("\n") + "\n")
            if Unused:
                raise ToolInputException(f"{self.Out}: no master line is marked for setting(s) {sorted(Unused)}")
            Body = "\n\n".join(Bodies)
            self.Parse(Body, self.Out)
            return self.Header(Body) + Body
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.Build(out={self.Out})")
            return ""

    def ReadPart(self, Part):
        if kS.ErrorMode:
            return ""
        try:
            Path = os.path.normpath(os.path.join(self.SharedRoot, Part))
            if not os.path.isfile(Path):
                raise ToolInputException(f"{self.Out}: master part not found: {Path}")
            with open(Path, encoding="utf-8") as File:
                Text = File.read().replace("\r\n", "\n")
            self.Parse(Text, Path)
            return Text
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.ReadPart(part={Part})")
            return ""

    def ApplySettings(self, Part, Text):
        """Replace the value of each assignment whose line carries "# kpy:setting <Name>" that the manifest sets.
        Returns the new text and the names applied. A value must be a str, int, float, bool or a list of str."""
        if kS.ErrorMode:
            return Text, set()
        try:
            Lines = Text.split("\n")
            Applied = set()
            for Node in ast.walk(ast.parse(Text)):
                if not isinstance(Node, ast.Assign):
                    continue
                Match = SETTING_PATTERN.search(Lines[Node.lineno - 1])
                if not Match or Match.group(1) not in self.Settings:
                    continue
                Name, Value = Match.group(1), self.Settings[Match.group(1)]
                IsTextList = isinstance(Value, list) and all(isinstance(Item, str) for Item in Value)
                if not isinstance(Value, (str, int, float, bool)) and not IsTextList:
                    raise ToolInputException(f"{self.Out}: setting {Name} must be text, a number, true/false "
                                             "or a list of text")
                if Node.value.lineno != Node.value.end_lineno:
                    raise ToolInputException(f"{Part}:{Node.lineno}: a kpy:setting value must be on one line")
                Line = Lines[Node.value.lineno - 1]
                Literal = json.dumps(Value, ensure_ascii=False) if isinstance(Value, (str, list)) else repr(Value)
                Lines[Node.value.lineno - 1] = (Line[:Node.value.col_offset] + Literal
                                                + Line[Node.value.end_col_offset:])
                Applied.add(Name)
            return "\n".join(Lines), Applied
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.ApplySettings(part={Part})")
            return Text, set()

    # A SyntaxError (bad input, exit 2) can only be told apart by catching it; any other error is still reported.
    # DOCUMENTED EXCEPTION: Python has no syntax test that does not raise.
    def Parse(self, Text, Name):
        if kS.ErrorMode:
            return
        try:
            ast.parse(Text, Name)
        except SyntaxError as e:
            raise ToolInputException(f"{Name}: not valid Python: {e}")
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.Parse(name={Name})")
            return

    def Header(self, Body):
        if kS.ErrorMode:
            return ""
        try:
            Parts = " + ".join(Part.replace(os.sep, "/") for Part in self.Parts)
            return (f"{HEADER_MARK} {COMPILER_VERSION} - DO NOT EDIT. Change the master and recompile.\n"
                    f"# Master: kSharedPy {kPyModule.MasterVersion(self.SharedRoot)}: {Parts}\n"
                    f"# Body SHA-256: {kPyModule.BodyHash(Body)}\n")
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyModule.Header")
            return ""

    @staticmethod
    def MasterVersion(SharedRoot):
        """The master's release (the VERSION file at its root), or "unversioned"."""
        if kS.ErrorMode:
            return ""
        try:
            Path = os.path.join(SharedRoot, "VERSION")
            if not os.path.isfile(Path):
                return "unversioned"
            with open(Path, encoding="utf-8") as File:
                return File.read().strip() or "unversioned"
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyModule.MasterVersion")
            return ""

    @staticmethod
    def VersionOnDisk(Text):
        """The master release named in a generated file's header, or ""."""
        if kS.ErrorMode:
            return ""
        try:
            Match = re.search(r"^# Master: kSharedPy (\S+):", Text or "", re.MULTILINE)
            return Match.group(1) if Match else ""
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyModule.VersionOnDisk")
            return ""

    @staticmethod
    def BodyHash(Body):
        if kS.ErrorMode:
            return ""
        try:
            return hashlib.sha256(Body.replace("\r\n", "\n").encode("utf-8")).hexdigest()
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyModule.BodyHash")
            return ""

    def OnDisk(self):
        """The output as it is now (LF), or None when there is no file."""
        if kS.ErrorMode:
            return None
        try:
            if not os.path.isfile(self.OutPath):
                return None
            with open(self.OutPath, encoding="utf-8") as File:
                return File.read().replace("\r\n", "\n")
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.OnDisk(out={self.Out})")
            return None

    def State(self, Fresh):
        """missing | not-generated | edited | stale | current. Fresh is the compiled text, or None (standalone)."""
        if kS.ErrorMode:
            return ""
        try:
            Current = self.OnDisk()
            if Current is None:
                return "missing"
            if not Current.startswith(HEADER_MARK):
                return "not-generated"
            Match = HASH_PATTERN.search(Current)
            Body = Current.split("\n", 3)[3] if Current.count("\n") >= 3 else ""
            if not Match or Match.group(1) != kPyModule.BodyHash(Body):
                return "edited"
            if Fresh is not None and Fresh != Current:
                return "stale"
            return "current"
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.State(out={self.Out})")
            return ""

    def Write(self, Text):
        if kS.ErrorMode:
            return
        try:
            os.makedirs(os.path.dirname(self.OutPath), exist_ok=True)
            with open(self.OutPath, "w", encoding="utf-8", newline="\n") as File:
                File.write(Text)
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyModule.Write(out={self.Out})")
            return


class kPyGates:
    """What must hold before any output is written: every master module an output imports is generated beside it,
    no output carries private material, and every master part follows the kShared error pattern."""

    def __init__(self, Manifest):
        try:
            self.Manifest = Manifest
            self.Problems = []
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyGates.__init__")

    def Run(self, Built):
        """Built: {kPyModule: generated text}. Raises ToolInputException listing every problem found."""
        if kS.ErrorMode:
            return
        try:
            MasterIndex = self.MasterIndex()
            Rules = self.PrivateRules()
            for Module, Text in Built.items():
                self.CheckImports(Module, Text, MasterIndex)
                self.CheckPrivate(Module, Text, Rules)
            self.CheckPattern()
            if self.Problems:
                raise ToolInputException("the compile gates refused:\n  " + "\n  ".join(self.Problems))
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyGates.Run")
            return

    def MasterIndex(self):
        """{module name: master path relative to SharedRoot} for every master .py (not tests, not scratch)."""
        if kS.ErrorMode:
            return {}
        try:
            Index = {}
            for Folder, SubFolders, Files in os.walk(self.Manifest.SharedRoot):
                SubFolders[:] = [Sub for Sub in SubFolders if not Sub.startswith((".", "_")) and Sub != "tests"]
                for Name in Files:
                    Path = os.path.join(Folder, Name)
                    if Name.endswith(".py") and not kPyGates.IsGenerated(Path):
                        Index.setdefault(Name[:-3], os.path.relpath(Path, self.Manifest.SharedRoot).replace(os.sep, "/"))
            return Index
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyGates.MasterIndex")
            return {}

    @staticmethod
    def IsGenerated(Path):
        """True for a generated copy inside the master (kSharedPy compiles its own folders): not a master."""
        if kS.ErrorMode:
            return False
        try:
            with open(Path, encoding="utf-8") as File:
                return File.readline().startswith(HEADER_MARK)
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyGates.IsGenerated(path={Path})")
            return False

    def CheckImports(self, Module, Text, MasterIndex):
        """An output that imports a master module needs that module beside it: generated, or the product's own."""
        if kS.ErrorMode:
            return
        try:
            Folders = [os.path.dirname(Module.OutPath)] + [os.path.normpath(os.path.join(self.Manifest.Dir, Extra))
                                                           for Extra in Module.ImportPaths]
            Outputs = {os.path.normcase(Other.OutPath) for Other in self.Manifest.Modules}
            for Node in ast.walk(ast.parse(Text)):
                Names = []
                if isinstance(Node, ast.Import):
                    Names = [Alias.name.split(".")[0] for Alias in Node.names]
                elif isinstance(Node, ast.ImportFrom) and Node.level == 0 and Node.module:
                    Names = [Node.module.split(".")[0]]
                for Name in Names:
                    if Name not in MasterIndex:
                        continue
                    Candidates = [os.path.join(Folder, Name + ".py") for Folder in Folders]
                    if not any(os.path.normcase(Path) in Outputs or os.path.isfile(Path) for Path in Candidates):
                        Beside = os.path.relpath(Candidates[0], self.Manifest.Dir).replace(os.sep, "/")
                        self.Problems.append(f"{Module.Out} imports {Name} (kSharedPy/{MasterIndex[Name]}): add it "
                                             f"to Modules with Out \"{Beside}\"")
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyGates.CheckImports(out={Module.Out})")
            return

    def PrivateRules(self):
        """Private paths, secrets in URLs, and the kPS client-name denylist (when it is beside the master) minus the
        manifest's AllowNames."""
        if kS.ErrorMode:
            return []
        try:
            Rules = [re.compile(Pattern) for Pattern in PRIVATE_PATTERNS]
            Denylist = os.path.join(os.path.dirname(self.Manifest.SharedRoot), "kPS", "kps.denylist.json")
            if os.path.isfile(Denylist):
                with open(Denylist, encoding="utf-8") as File:
                    Terms = [Entry["Term"] for Entry in json.load(File).get("Terms", [])]
                Allowed = {Name.lower() for Name in self.Manifest.AllowNames}
                Rules += [re.compile(rf"(?<![A-Za-z0-9]){re.escape(Term)}", re.IGNORECASE)
                          for Term in Terms if Term.lower() not in Allowed]
            return Rules
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyGates.PrivateRules")
            return []

    def CheckPrivate(self, Module, Text, Rules):
        if kS.ErrorMode:
            return
        try:
            for Number, Line in enumerate(Text.split("\n"), 1):
                for Rule in Rules:
                    if Rule.search(Line):
                        self.Problems.append(f"{Module.Out}:{Number}: private material ({Rule.pattern})")
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyGates.CheckPrivate(out={Module.Out})")
            return

    def CheckPattern(self):
        """Every master part follows the error pattern (kpy/check_kpattern.py, the same audit products run)."""
        if kS.ErrorMode:
            return
        try:
            from check_kpattern import kPatternAudit
            Parts = sorted({os.path.normpath(os.path.join(self.Manifest.SharedRoot, Part))
                            for Module in self.Manifest.Modules for Part in Module.Parts})
            for Path in Parts:
                for Finding in kPatternAudit(Path).Run():
                    self.Problems.append(f"error pattern: {Finding}")
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyGates.CheckPattern")
            return


class kPyManifest:
    """A product's kpy.manifest.json: where the master is and which modules to generate."""

    def __init__(self, Path, SharedRootOverride="", Standalone=False):
        try:
            if not os.path.isfile(Path):
                raise ToolInputException(f"manifest not found: {Path}")
            with open(Path, encoding="utf-8") as File:
                try:
                    Data = json.load(File)
                except json.JSONDecodeError as e:
                    raise ToolInputException(f"{Path}: not valid JSON: {e}")
            self.Path = os.path.abspath(Path)
            self.Dir = os.path.dirname(self.Path)
            self.Product = Data.get("Product", "")
            self.AllowNames = list(Data.get("AllowNames", []))
            Root = SharedRootOverride or os.environ.get("KPY_SHARED_ROOT", "") or Data.get("SharedRoot", "")
            self.SharedRoot = os.path.normpath(os.path.join(self.Dir, Root)) if Root else ""
            if not Standalone and not os.path.isdir(self.SharedRoot or "?"):
                raise ToolInputException(f"the kSharedPy master is not at \"{self.SharedRoot}\" - set SharedRoot, "
                                         "--shared-root or KPY_SHARED_ROOT, or verify with --standalone")
            if not isinstance(Data.get("Modules"), list) or not Data["Modules"]:
                raise ToolInputException(f"{Path}: \"Modules\" must be a non-empty list")
            self.Modules = [kPyModule(Entry, self.Dir, self.SharedRoot) for Entry in Data["Modules"]]
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, f"kPyManifest.__init__(path={Path})")


class kPyReport:
    """Every product under a folder: which master release each was compiled from, and what is not current."""

    SKIP = {"node_modules", ".git", "_scratch", "_archive", "__pycache__", ".venv", "out"}

    def __init__(self, Root, SharedRootOverride=""):
        try:
            self.Root = os.path.abspath(Root)
            self.SharedRootOverride = SharedRootOverride
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyReport.__init__")

    def Manifests(self):
        if kS.ErrorMode:
            return []
        try:
            Found, Seen = [], set()
            for Folder, SubFolders, Files in os.walk(self.Root):
                SubFolders[:] = [Sub for Sub in SubFolders if Sub not in kPyReport.SKIP]
                Real = os.path.normcase(os.path.realpath(Folder))  # a linked folder (.agents\skills) counts once
                if "kpy.manifest.json" in Files and Real not in Seen:
                    Seen.add(Real)
                    Found.append(os.path.join(Folder, "kpy.manifest.json"))
            return sorted(Found)
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyReport.Manifests")
            return []

    def Run(self):
        """Print one line per product; returns 5 when any product is behind, else 0."""
        if kS.ErrorMode:
            return 1
        try:
            Behind = 0
            for Path in self.Manifests():
                Manifest = kPyManifest(Path, self.SharedRootOverride)
                States, Versions = {}, set()
                for Module in Manifest.Modules:
                    State = Module.State(Module.Build())
                    States[State] = States.get(State, 0) + 1
                    Versions.add(kPyModule.VersionOnDisk(Module.OnDisk()) or "-")
                Current = kPyModule.MasterVersion(Manifest.SharedRoot)
                Summary = ", ".join(f"{Count} {State}" for State, Count in sorted(States.items()))
                Behind += set(States) != {"current"}
                print(f"{Manifest.Product or Path}: {Summary}; compiled from kSharedPy {'/'.join(sorted(Versions))}"
                      f" (master {Current})  [{os.path.relpath(Path, self.Root)}]")
            return EXIT_VERIFY_FAILED if Behind else 0
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyReport.Run")
            return 1


class kPyCompilerApp:
    """The command line: Check, Compile, Verify."""

    def Run(self):
        if kS.ErrorMode:
            return 1
        try:
            Parser = argparse.ArgumentParser(description="Generate a product's Python modules from kSharedPy.")
            Parser.add_argument("--manifest", default="")
            Parser.add_argument("--action", choices=["check", "compile", "verify", "report"], default="check")
            Parser.add_argument("--root", default="", help="report: the folder searched for kpy.manifest.json files")
            Parser.add_argument("--shared-root", default="")
            Parser.add_argument("--adopt", action="store_true",
                                help="compile may replace an output that is not a generated file yet")
            Parser.add_argument("--standalone", action="store_true",
                                help="verify only the body hashes; the master is not needed")
            Args = Parser.parse_args()
            if Args.standalone and Args.action != "verify":
                raise ToolInputException("--standalone only goes with --action verify")
            if Args.action == "report":
                if not Args.root or not os.path.isdir(Args.root):
                    raise ToolInputException("--action report needs --root <folder that holds the products>")
                return kPyReport(Args.root, Args.shared_root).Run()
            if not Args.manifest:
                raise ToolInputException("--manifest is required (except with --action report)")
            Manifest = kPyManifest(Args.manifest, Args.shared_root, Args.standalone)
            Built = {}
            if not Args.standalone:
                for Module in Manifest.Modules:
                    Built[Module] = Module.Build()
                kPyGates(Manifest).Run(Built)
            Problems = 0
            for Module in Manifest.Modules:
                Fresh = Built.get(Module)
                State = Module.State(Fresh)
                if Args.action == "compile" and State != "current":
                    if State in ("not-generated", "edited") and not Args.adopt:
                        raise ToolReportableException(
                            f"{Module.Out} is {State}: a hand change would be lost. Port it into the master, "
                            "then run again with --adopt.")
                    Module.Write(Fresh)
                    print(f"written   {Module.Out}  (was {State})")
                    continue
                print(f"{State:<9} {Module.Out}")
                Problems += State != "current"
            if Args.action == "verify" and Problems:
                raise ToolReportableException(
                    f"{Problems} generated module(s) are not current. The master is kSharedPy "
                    "(https://github.com/PeterKalmstrom/kSharedPy); change it there and recompile.",
                    EXIT_VERIFY_FAILED)
            return 0
        except kToolException:
            raise
        except Exception as e:
            kS.GlobalErrorHandler(e, "kPyCompilerApp.Run")
            return 1


if __name__ == "__main__":
    kRun.Main(kPyCompilerApp)
