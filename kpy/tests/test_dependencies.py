"""Every runnable master script declares its dependencies in a PEP 723 header that matches its real imports.

Run: python -m unittest discover -s X:\\Source\\Admin\\kSharedPy\\kpy\\tests -v

`uv run <script>.py` installs what the `# /// script` block lists, so the block must cover every third-party import
of the script AND of the master modules it imports (kGenAi -> google-genai, kFfmpeg -> static-ffmpeg, _ppt ->
pywin32, ...), including imports made by name (importlib.import_module / find_spec / kDependency.Has). A package
that a script only uses on demand, with a fallback or a clear message, goes on OPTIONAL below with the reason.
Generated copies (# GENERATED by kPyCompiler) and library modules without a __main__ block are not scripts.
"""
import ast
import os
import re
import sys
import tomllib
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCRIPT_FOLDERS = ["gemini", "veo", "vedit", "powerpoint", "kpy"]
MASTER_FOLDER = "kshared"  # the master of the shared modules every folder receives generated copies of

# The reference regex from PEP 723 (https://peps.python.org/pep-0723/#reference-implementation)
PEP723_REGEX = r"(?m)^# /// (?P<type>[a-zA-Z0-9-]+)$\s(?P<content>(^#(| .*)$\s)+)^# ///$"

# import name (dotted prefixes are tried longest first) -> PyPI package name
PACKAGE_OF = {
    "google.genai": "google-genai",
    "google": "google-genai",       # kGenAi probes find_spec("google") before "google.genai"
    "win32com": "pywin32",
    "pythoncom": "pywin32",
    "pywintypes": "pywin32",
    "PIL": "pillow",
    "static_ffmpeg": "static-ffmpeg",
    "faster_whisper": "faster-whisper",
    "silero_vad": "silero-vad",
    "pptx": "python-pptx",
    "numpy": "numpy",
}

# (script, package) -> why the script works without it; run with `uv run --with <package> <script>.py` when needed
OPTIONAL = {
    ("veo/batch_video_gen.py", "static-ffmpeg"):
        "only --mute needs ffmpeg, and ffmpeg on PATH is enough; the script checks before the first paid call",
    ("vedit/propose.py", "silero-vad"):
        "only --vad-engine silero; pulls torch; checked with kDependency.Has and a clear exit-2 message",
    ("vedit/subtitles.py", "static-ffmpeg"):
        "imports only kDependency from kFfmpeg - it never runs ffmpeg",
}

DYNAMIC_IMPORTERS = {"import_module", "find_spec", "Has"}  # calls whose first literal argument names a module


class kScriptScanner:
    """Finds the runnable master scripts and the third-party packages each one needs."""

    @staticmethod
    def IsGenerated(Path):
        with open(Path, encoding="utf-8") as File:
            return File.readline().startswith("# GENERATED by kPyCompiler")

    @staticmethod
    def Source(Path):
        with open(Path, encoding="utf-8") as File:
            return File.read()

    @staticmethod
    def IsRunnable(Source):
        return re.search(r"""^if __name__ == ["']__main__["']:""", Source, re.MULTILINE) is not None

    @staticmethod
    def Scripts():
        """Relative paths (forward slashes) of every runnable master script in SCRIPT_FOLDERS."""
        Result = []
        for Folder in SCRIPT_FOLDERS:
            for Name in sorted(os.listdir(os.path.join(ROOT, Folder))):
                Path = os.path.join(ROOT, Folder, Name)
                if not Name.endswith(".py") or not os.path.isfile(Path) or kScriptScanner.IsGenerated(Path):
                    continue
                if kScriptScanner.IsRunnable(kScriptScanner.Source(Path)):
                    Result.append(f"{Folder}/{Name}")
        return Result

    @staticmethod
    def Header(Source):
        """The parsed `script` block, or None. More than one block is an error (PEP 723)."""
        Blocks = [Match for Match in re.finditer(PEP723_REGEX, Source) if Match.group("type") == "script"]
        if len(Blocks) > 1:
            raise ValueError("multiple script blocks")
        if not Blocks:
            return None
        Content = "".join(Line[2:] if Line.startswith("# ") else Line[1:]
                          for Line in Blocks[0].group("content").splitlines(keepends=True))
        return tomllib.loads(Content)

    @staticmethod
    def PackageName(Requirement):
        """'pywin32; sys_platform == "win32"' -> 'pywin32'; 'pillow>=10' -> 'pillow'."""
        return re.match(r"\s*([A-Za-z0-9._-]+)", Requirement).group(1).lower().replace("_", "-")

    @staticmethod
    def ModuleNames(Source):
        """Every module the code imports: import statements plus literal names passed to importlib / Has()."""
        Names = set()
        for Node in ast.walk(ast.parse(Source)):
            if isinstance(Node, ast.Import):
                Names.update(Alias.name for Alias in Node.names)
            elif isinstance(Node, ast.ImportFrom) and Node.level == 0 and Node.module:
                Names.add(Node.module)
            elif isinstance(Node, ast.Call) and Node.args and isinstance(Node.args[0], ast.Constant) \
                    and isinstance(Node.args[0].value, str):
                Func = Node.func
                FuncName = Func.attr if isinstance(Func, ast.Attribute) else getattr(Func, "id", "")
                if FuncName in DYNAMIC_IMPORTERS and not Node.args[0].value.startswith("."):
                    Names.add(Node.args[0].value)
        return Names

    @staticmethod
    def LocalModule(Folder, Name):
        """The master file of a local module (kshared master first, else a sibling in the folder), or None."""
        for Candidate in (os.path.join(ROOT, MASTER_FOLDER, Name + ".py"), os.path.join(ROOT, Folder, Name + ".py")):
            if os.path.isfile(Candidate):
                return Candidate
        return None

    @staticmethod
    def Package(Name):
        Parts = Name.split(".")
        for Length in range(len(Parts), 0, -1):
            Prefix = ".".join(Parts[:Length])
            if Prefix in PACKAGE_OF:
                return PACKAGE_OF[Prefix]
        return None

    @staticmethod
    def Needs(Script):
        """{package: [where it comes from]} for the script and every local module it reaches; also the unmapped."""
        Folder = Script.split("/")[0]
        Needed, Unmapped, Seen = {}, set(), set()
        Pending = [os.path.join(ROOT, *Script.split("/"))]
        while Pending:
            Path = Pending.pop()
            if Path in Seen:
                continue
            Seen.add(Path)
            for Name in kScriptScanner.ModuleNames(kScriptScanner.Source(Path)):
                Top = Name.split(".")[0]
                if Top in sys.stdlib_module_names or Top == "__future__":
                    continue
                Local = kScriptScanner.LocalModule(Folder, Top)
                if Local:
                    Pending.append(Local)
                    continue
                Package = kScriptScanner.Package(Name)
                if Package is None:
                    Unmapped.add(f"{Name} (in {os.path.relpath(Path, ROOT)})")
                else:
                    Needed.setdefault(Package, []).append(os.path.relpath(Path, ROOT))
        return Needed, Unmapped


class kDependencyHeaderTests(unittest.TestCase):

    def test_ScriptsAreFound(self):
        Scripts = kScriptScanner.Scripts()
        for Expected in ("gemini/batch_image_gen.py", "vedit/propose.py", "powerpoint/contact_sheet.py",
                         "kpy/kPyCompiler.py", "kpy/check_kpattern.py"):
            self.assertIn(Expected, Scripts)
        self.assertNotIn("gemini/kShared.py", Scripts)  # generated copy
        self.assertNotIn("powerpoint/_ppt.py", Scripts)  # library module

    def test_EveryScriptHasAHeader(self):
        for Script in kScriptScanner.Scripts():
            with self.subTest(script=Script):
                Header = kScriptScanner.Header(kScriptScanner.Source(os.path.join(ROOT, *Script.split("/"))))
                self.assertIsNotNone(Header, f"{Script}: no '# /// script' block")
                self.assertEqual(Header.get("requires-python"), ">=3.10")
                self.assertIsInstance(Header.get("dependencies"), list)

    def test_DependenciesCoverImports(self):
        for Script in kScriptScanner.Scripts():
            with self.subTest(script=Script):
                Header = kScriptScanner.Header(kScriptScanner.Source(os.path.join(ROOT, *Script.split("/")))) or {}
                Declared = {kScriptScanner.PackageName(Item) for Item in Header.get("dependencies", [])}
                Needed, Unmapped = kScriptScanner.Needs(Script)
                self.assertEqual(Unmapped, set(), f"{Script}: third-party import with no package in PACKAGE_OF")
                Missing = {Package: Sources for Package, Sources in Needed.items()
                           if Package not in Declared and (Script, Package) not in OPTIONAL}
                self.assertEqual(Missing, {}, f"{Script}: imports not declared in its PEP 723 dependencies")

    def test_OptionalEntriesAreRealAndNotDeclared(self):
        for (Script, Package), Reason in OPTIONAL.items():
            with self.subTest(script=Script, package=Package):
                self.assertTrue(Reason)
                Needed, _Unmapped = kScriptScanner.Needs(Script)
                self.assertIn(Package, Needed, "stale OPTIONAL entry: the script no longer imports it")
                Header = kScriptScanner.Header(kScriptScanner.Source(os.path.join(ROOT, *Script.split("/"))))
                Declared = {kScriptScanner.PackageName(Item) for Item in Header["dependencies"]}
                self.assertNotIn(Package, Declared, "an optional package must not be in dependencies")

    def test_ReferenceRegexParsesASample(self):
        Sample = '"""Doc."""\n# /// script\n# requires-python = ">=3.10"\n# dependencies = ["pillow"]\n# ///\n'
        self.assertEqual(kScriptScanner.Header(Sample)["dependencies"], ["pillow"])
        self.assertIsNone(kScriptScanner.Header('"""No header."""\n'))
        self.assertEqual(kScriptScanner.PackageName("pywin32; sys_platform == 'win32'"), "pywin32")


if __name__ == "__main__":
    unittest.main()
