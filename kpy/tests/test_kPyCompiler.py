"""Tests for kPyCompiler. Run: python -m unittest discover -s X:\\Source\\Admin\\kSharedPy\\kpy\\tests -v

Every test builds a throwaway master and product under kSharedPy\\_scratch\\kpy-tests (never the user profile) and
runs the compiler as a real process, so exit codes and messages are what a person and CI see.
"""
import json
import os
import shutil
import subprocess
import sys
import unittest
import uuid

KPY = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPILER = os.path.join(KPY, "kPyCompiler.py")
SCRATCH = os.path.join(os.path.dirname(KPY), "_scratch", "kpy-tests")

MASTER_PART = '''"""A master part."""


class kThing:
    Product = "master"  # kpy:setting Product
    Size = 1  # kpy:setting Size
    Fixed = "left alone"
'''


class kPyCompilerTests(unittest.TestCase):

    def setUp(self):
        self.Root = os.path.join(SCRATCH, uuid.uuid4().hex[:8])
        self.Master = os.path.join(self.Root, "master")
        self.Product = os.path.join(self.Root, "product")
        os.makedirs(os.path.join(self.Master, "kshared"))
        os.makedirs(self.Product)
        self.WriteMaster("kshared/kThing.py", MASTER_PART)
        self.WriteManifest({"Out": "scripts/kThing.py", "Parts": ["kshared/kThing.py"],
                            "Settings": {"Product": "my-product", "Size": 3}})

    def tearDown(self):
        shutil.rmtree(self.Root, ignore_errors=True)

    def WriteMaster(self, Rel, Text):
        with open(os.path.join(self.Master, Rel), "w", encoding="utf-8", newline="\n") as File:
            File.write(Text)

    def WriteManifest(self, *Modules):
        self.Manifest = os.path.join(self.Product, "kpy.manifest.json")
        with open(self.Manifest, "w", encoding="utf-8") as File:
            json.dump({"Product": "test", "SharedRoot": "../master", "Modules": list(Modules)}, File)

    def Compiler(self, *Args):
        Env = dict(os.environ, KPY_ERROR_REPORT="0", KPS_ERROR_REPORT="0")
        Env.pop("KPY_SHARED_ROOT", None)
        return subprocess.run([sys.executable, COMPILER, "--manifest", self.Manifest, *Args],
                              capture_output=True, text=True, env=Env, stdin=subprocess.DEVNULL)

    def Output(self):
        with open(os.path.join(self.Product, "scripts", "kThing.py"), encoding="utf-8") as File:
            return File.read()

    def test_check_is_read_only_and_reports_missing(self):
        Result = self.Compiler()
        self.assertEqual(Result.returncode, 0, Result.stderr)
        self.assertIn("missing", Result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.Product, "scripts")))

    def test_compile_applies_settings_and_verify_passes(self):
        self.assertEqual(self.Compiler("--action", "compile").returncode, 0)
        Text = self.Output()
        self.assertTrue(Text.startswith("# GENERATED by kPyCompiler"))
        self.assertIn('Product = "my-product"  # kpy:setting Product', Text)
        self.assertIn("Size = 3  # kpy:setting Size", Text)
        self.assertIn('Fixed = "left alone"', Text)
        self.assertEqual(self.Compiler("--action", "verify").returncode, 0)
        self.assertEqual(self.Compiler("--action", "verify", "--standalone").returncode, 0)

    def test_hand_edit_fails_verify_and_blocks_compile(self):
        self.Compiler("--action", "compile")
        Path = os.path.join(self.Product, "scripts", "kThing.py")
        with open(Path, "a", encoding="utf-8") as File:
            File.write("# a hand edit\n")
        Result = self.Compiler("--action", "verify", "--standalone")
        self.assertEqual(Result.returncode, 5)
        self.assertIn("edited", Result.stdout)
        self.assertEqual(self.Compiler("--action", "compile").returncode, 1)
        self.assertIn("# a hand edit", self.Output())
        self.assertEqual(self.Compiler("--action", "compile", "--adopt").returncode, 0)
        self.assertNotIn("# a hand edit", self.Output())

    def test_crlf_checkout_is_not_a_hand_edit(self):
        self.Compiler("--action", "compile")
        Path = os.path.join(self.Product, "scripts", "kThing.py")
        Text = self.Output()
        with open(Path, "w", encoding="utf-8", newline="\r\n") as File:
            File.write(Text)
        self.assertEqual(self.Compiler("--action", "verify").returncode, 0)

    def test_master_change_makes_output_stale(self):
        self.Compiler("--action", "compile")
        self.WriteMaster("kshared/kThing.py", MASTER_PART + "    Extra = 2\n")
        Result = self.Compiler("--action", "verify")
        self.assertEqual(Result.returncode, 5)
        self.assertIn("stale", Result.stdout)

    def test_hand_copy_needs_adopt(self):
        os.makedirs(os.path.join(self.Product, "scripts"))
        with open(os.path.join(self.Product, "scripts", "kThing.py"), "w", encoding="utf-8") as File:
            File.write("x = 1\n")
        Result = self.Compiler("--action", "compile")
        self.assertEqual(Result.returncode, 1)
        self.assertIn("not-generated", Result.stderr)

    def test_list_setting_and_bad_type(self):
        self.WriteManifest({"Out": "scripts/kThing.py", "Parts": ["kshared/kThing.py"],
                            "Settings": {"Product": ["a", "b"]}})
        self.assertEqual(self.Compiler("--action", "compile").returncode, 0)
        self.assertIn('Product = ["a", "b"]  # kpy:setting Product', self.Output())
        self.WriteManifest({"Out": "scripts/kThing.py", "Parts": ["kshared/kThing.py"],
                            "Settings": {"Product": {"a": 1}}})
        self.assertEqual(self.Compiler().returncode, 2)

    def test_unknown_setting_is_bad_input(self):
        self.WriteManifest({"Out": "scripts/kThing.py", "Parts": ["kshared/kThing.py"], "Settings": {"Nope": 1}})
        Result = self.Compiler()
        self.assertEqual(Result.returncode, 2)
        self.assertIn("Nope", Result.stderr)

    def test_output_outside_product_is_bad_input(self):
        self.WriteManifest({"Out": "../escape.py", "Parts": ["kshared/kThing.py"]})
        self.assertEqual(self.Compiler().returncode, 2)

    def test_invalid_master_is_bad_input(self):
        self.WriteMaster("kshared/kThing.py", "def broken(:\n")
        Result = self.Compiler()
        self.assertEqual(Result.returncode, 2)
        self.assertIn("not valid Python", Result.stderr)

    def test_parts_are_joined_and_future_only_first(self):
        self.WriteMaster("kshared/kMore.py", "from __future__ import annotations\nY = 2\n")
        self.WriteManifest({"Out": "scripts/kThing.py", "Parts": ["kshared/kThing.py", "kshared/kMore.py"]})
        self.assertEqual(self.Compiler().returncode, 2)
        self.WriteMaster("kshared/kMore.py", "Y = 2\n")
        self.assertEqual(self.Compiler("--action", "compile").returncode, 0)
        self.assertIn("Y = 2", self.Output())
        self.assertIn("# Master: kSharedPy/kshared/kThing.py + kSharedPy/kshared/kMore.py", self.Output())

    def test_missing_master_says_how_to_fix(self):
        shutil.rmtree(self.Master)
        Result = self.Compiler("--action", "verify")
        self.assertEqual(Result.returncode, 2)
        self.assertIn("--standalone", Result.stderr)


if __name__ == "__main__":
    unittest.main()
